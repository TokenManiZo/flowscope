import { expect, test } from "@playwright/test"

test("project start URL and literal wildcard scope survive editing and reopening", async ({ page }, info) => {
  const name = `start-url-${Date.now()}`
  await page.addInitScript(() => localStorage.setItem("flowscope.sidebar", "open"))
  await page.goto("./")
  await page.getByRole("button", { name: "프로젝트 관리", exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "프로젝트 관리", exact: true })
  await dialog.getByRole("tab", { name: "새 프로젝트" }).click()
  const site = dialog.getByRole("textbox", { name: "시작할 사이트 주소", exact: true })
  await site.fill("*.example.test")
  await site.blur()
  await expect(site).toHaveValue("")
  await expect(dialog.getByText("*.example.test:443", { exact: true })).toBeVisible()
  await expect(dialog.getByRole("button", { name: "프로젝트 만들고 열기" })).toBeDisabled()
  await site.fill("https://mobile.example.test/login?next=home")
  await dialog.getByRole("textbox", { name: "프로젝트 이름", exact: true }).fill(name)
  await dialog.getByRole("button", { name: "시작할 사이트 주소 설명" }).click()
  await expect(page.getByText(/이 주소로 브라우저를 열어요/)).toBeVisible()
  await expect(page.locator("[data-slot=popover-content]")).toHaveCSS("opacity", "1")
  await page.screenshot({ path: info.outputPath("create-help.png") })
  await page.keyboard.press("Escape")
  const created = page.waitForResponse(response => response.url().endsWith("/api/projects") && response.request().method() === "POST")
  await dialog.getByRole("button", { name: "프로젝트 만들고 열기" }).click()
  expect((await created).status()).toBe(200)
  await expect(dialog.getByText("https://mobile.example.test/login?next=home", { exact: true })).toBeVisible()
  await dialog.getByRole("button", { name: "수정", exact: true }).click()
  await site.fill("https://mobile.example.test/login?next=updated")
  await page.screenshot({ path: info.outputPath("edit-desktop.png") })
  await page.setViewportSize({ width: 360, height: 800 })
  await page.screenshot({ path: info.outputPath("edit-mobile.png") })
  expect(await dialog.evaluate(element => element.scrollWidth - element.clientWidth)).toBeLessThan(3)
  await dialog.getByRole("button", { name: "변경 저장" }).click()
  await expect(dialog.getByText("https://mobile.example.test/login?next=updated", { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 1280, height: 800 })
  await dialog.getByRole("tab", { name: "새 프로젝트" }).click()
  await site.fill("https://other.example.test/")
  await dialog.getByRole("textbox", { name: "프로젝트 이름", exact: true }).fill(`${name}-other`)
  await dialog.getByRole("button", { name: "프로젝트 만들고 열기" }).click()
  await dialog.getByRole("button", { name: `${name} 열기` }).click()
  await dialog.getByRole("button", { name: "전환", exact: true }).click()
  await expect(dialog.getByText("https://mobile.example.test/login?next=updated", { exact: true })).toBeVisible()
  await expect(dialog.getByText("https://*.example.test:443/", { exact: true })).toBeVisible()
  await expect(dialog.getByText(/%2A/i)).toHaveCount(0)
})
